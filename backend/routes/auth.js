// Special admin registration endpoint (temporary for setup)
router.post('/register-admin', [
  body('name')
    .trim()
    .isLength({ min: 2, max: 50 })
    .withMessage('Name must be between 2 and 50 characters'),
  body('email')
    .isEmail()
    .normalizeEmail()
    .withMessage('Please provide a valid email'),
  body('password')
    .isLength({ min: 6 })
    .withMessage('Password must be at least 6 characters long'),
  body('phone')
    .optional()
    .matches(/^[0-9]{10}$/)
    .withMessage('Please provide a valid 10-digit phone number')
], async (req, res) => {
  try {
    console.log('Admin registration request received:', req.body);
    
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
      console.log('Validation errors:', errors.array());
      return res.status(400).json({
        success: false,
        message: 'Validation failed',
        errors: errors.array()
      });
    }

    const { name, email, password, phone } = req.body;
    console.log('Processing admin registration for:', { name, email, phone });

    // Check if user already exists
    const existingUser = await User.findOne({ email });
    if (existingUser) {
      console.log('User already exists with email:', email);
      
      // Update existing user to admin role
      existingUser.role = 'admin';
      existingUser.isActive = true;
      existingUser.isVerified = true;
      await existingUser.save();
      
      const userResponse = existingUser.toObject();
      delete userResponse.password;
      
      return res.json({
        success: true,
        message: 'Existing user updated to admin role',
        data: { user: userResponse }
      });
    }

    console.log('Creating new admin user...');
    // Create new admin user
    const user = new User({
      name,
      email,
      password,
      role: 'admin', // Force admin role
      phone,
      isVerified: true,
      isActive: true
    });

    console.log('Saving admin user to database...');
    await user.save();
    console.log('Admin user saved successfully!');

    // Generate tokens
    const token = generateToken(user._id);
    const refreshToken = generateRefreshToken(user._id);

    // Remove password from response
    const userResponse = user.toObject();
    delete userResponse.password;

    res.status(201).json({
      success: true,
      message: 'Admin user registered successfully',
      data: {
        user: userResponse,
        token,
        refreshToken
      }
    });

  } catch (error) {
    console.error('Admin registration error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error during admin registration'
    });
  }
});

